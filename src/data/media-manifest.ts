/**
 * MISSION MEDIA MANIFEST
 * ======================
 *
 * Every still and every clip that ECHOES shows for a mission is listed here
 * with its provenance: the official NASA page it came from, the direct asset
 * URL, the credit, the mission it belongs to, an honest media classification,
 * the date it was retrieved and its usage restrictions.
 *
 * The files themselves live in `public/media/missions/<slug>/` and are served
 * from the application root, so they work unchanged at a domain root or under
 * the GitHub Pages sub-path (see `src/lib/asset.ts`). NOTHING here is fetched
 * from the network at runtime: the NASA Image and Video Library was used once,
 * during curation, to locate and verify the assets; the application itself
 * never calls it.
 *
 * HONESTY RULES OBSERVED IN THIS MANIFEST
 *  - An asset is only listed under a mission if NASA's own metadata for it
 *    names that mission. Images of one planet mission are never used to
 *    illustrate another.
 *  - Every still is classified: "Archival photograph" (a photograph of the
 *    mission or its site), "Mission camera image" (recorded by the mission's
 *    own camera), "Scientific visualization" (a rendered or data-derived
 *    view), "Other illustration" (a map or diagram) or "Artist's concept".
 *  - Where an authentic short video does not exist, the gap is left visible
 *    instead of being filled with an unrelated clip.
 *
 * ECHOES is an independent project. It is not an official NASA product and is
 * not endorsed by NASA, JPL or any other centre named in the credits.
 */

/** How an asset was made. Never guess: an artist's concept is not a photo. */
export type MediaClassification =
  | "Archival photograph"
  | "Mission camera image"
  | "Mission video"
  | "Scientific visualization"
  | "Artist's concept"
  | "Other illustration";

/** How the asset is delivered. */
export type MediaKind = "image" | "video" | "external-video";

/** Where the asset sits in the mission media presentation. */
export type MediaRole = "hero" | "gallery" | "video" | "journey";

export interface MissionMediaAsset {
  /** NASA's own identifier for the asset (e.g. "PIA16120"), or a local id. */
  id: string;
  kind: MediaKind;
  classification: MediaClassification;
  role: MediaRole;
  /** Official asset title. */
  title: string;
  /** One or two sentences of mission context, written for ECHOES. */
  caption: string;
  /** Path served from the application root (files live in `public/`). */
  file?: string;
  /** Small variant for gallery tiles and mobile. */
  thumb?: string;
  /** Poster frame for a video. */
  poster?: string;
  width?: number;
  height?: number;
  thumbWidth?: number;
  /** External playback or source link (used only when nothing is stored). */
  url?: string;
  /** The official page describing the asset. */
  sourcePage: string;
  /** The direct asset URL at the source, when one exists. */
  directUrl?: string;
  /** NASA centre, agency or creator credit. */
  credit: string;
  /** Date the asset was retrieved (ISO). */
  accessed: string;
  /** Copyright / usage restriction recorded for this asset. */
  restrictions: string;
}

export interface MissionMediaCollection {
  /** Device id this collection belongs to (matches the mission registry). */
  deviceId: string;
  label: string;
  assets: MissionMediaAsset[];
}

