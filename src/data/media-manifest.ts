const BY_DEVICE = new Map(MISSION_MEDIA.map((c) => [c.deviceId, c]));

/** The media collection for a device, or null when it has none. */
export const mediaForDevice = (deviceId?: string | null): MissionMediaCollection | null => {
  if (!deviceId) return null;
  return BY_DEVICE.get(deviceId) ?? null;
};

/** Every asset registered for a device (hero, gallery, video, journey). */
export const mediaAssetsForDevice = (deviceId?: string | null): MissionMediaAsset[] =>
  mediaForDevice(deviceId)?.assets ?? [];

/** The hero image of a device, if it has one. */
export const heroForDevice = (deviceId?: string | null): MissionMediaAsset | null =>
  mediaAssetsForDevice(deviceId).find((a) => a.role === "hero" && a.kind === "image") ?? null;

/** The supporting gallery of a device. */
export const galleryForDevice = (deviceId?: string | null): MissionMediaAsset[] =>
  mediaAssetsForDevice(deviceId).filter((a) => a.role === "gallery" && a.kind === "image");

/** The video registered for a device (stored locally, or an external source). */
export const videoForDevice = (deviceId?: string | null): MissionMediaAsset | null =>
  mediaAssetsForDevice(deviceId).find((a) => a.role === "video") ?? null;

/** Chapter imagery used inside a mission journey. */
export const journeyMediaForDevice = (deviceId?: string | null): MissionMediaAsset[] =>
  mediaAssetsForDevice(deviceId).filter((a) => a.role === "journey");

